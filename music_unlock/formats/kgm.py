DEFAULT_KEY_PATH = Path(__file__).resolve().parents[2] / "assets" / "kugou_key.xz"


def _scramble(value: int) -> int:
    """公开的字节变换：value ^ ((value & 0x0F) << 4)。"""
    return value ^ ((value & 0x0F) << 4)


def _inverse_scramble(value: int, xor: int) -> int:
    """_scramble(x ^ xor) == value 时的 x。"""
    low = value & 0x0F
    high = (value >> 4) & 0x0F
    return (((high ^ low) << 4) | low) ^ xor


class KgmDecoder(Decoder):
    name = "酷狗音乐 KGM"
    extensions = frozenset({".kgm", ".kgma", ".vpr", ".kgm.flac", ".vpr.flac"})

    def __init__(self):
        self._phase_cache: dict[tuple, tuple] = {}

    # -- 组合查找表：给定相位与列，输出 [pub_value][cipher_byte] -> plain --
    def _phase_tables(self, phase: int, own_key: bytes, pub_key: bytes) -> tuple:
        cache_key = (phase, own_key, pub_key)
        cached = self._phase_cache.get(cache_key)
        if cached is not None:
            return cached
        mend = len(MEND_TABLE)
        columns = []
        for col in range(BLOCK):
            own_idx = (phase * BLOCK + col) % OWN_KEY_LEN
            pub_idx = (phase * BLOCK + col) % mend
            table = []
            for pub_value in range(256):  # pub_value 是单字节，只有 256 种取值
                xormask = _scramble(pub_value ^ MEND_TABLE[pub_idx])
                # 解密：plain = forward_own_table(cipher) ^ pub掩码
                table.append(bytes(_scramble(v ^ own_key[own_idx]) ^ xormask for v in range(256)))
            columns.append(table)
        tables = tuple(columns)
        self._phase_cache[cache_key] = tables
        return tables

    def decode(self, path: Path, opts: DecodeOptions) -> DecodeResult:
        data = path.read_bytes()
        if len(data) < HEADER_LEN + 16:
            raise FormatError(f"{path.name}: 文件过短")
        header = data[:HEADER_LEN]
        magic = header[:16]
        if magic != KGM_MAGIC and magic != VPR_MAGIC:
            raise FormatError(f"{path.name}: 不是 KGM/VPR 文件")

        audio_offset = int.from_bytes(header[0x10:0x14], "little")
        crypto_version = int.from_bytes(header[0x14:0x18], "little")
        crypto_test = header[0x1C:0x2C]  # 16 字节自检密钥材料

        if crypto_version == 5:
            raise UnsupportedError(f"{path.name}: KGG(v5) 需要客户端密钥库，暂不支持")

        key_path = opts.kgm_key or DEFAULT_KEY_PATH
        try:
            pub_key = lzma.decompress(Path(key_path).read_bytes())
        except FileNotFoundError:
            raise FormatError(f"缺少酷狗公钥文件: {key_path}（可用 --kgm-key 指定）") from None

        own_key = crypto_test + b"\x00"  # 17 字节
        audio = bytearray(data[audio_offset:])
        pub_len = len(pub_key)
        out = bytearray(len(audio))
        # 16 字节一块处理：块内 pub_value 恒定，相位 = 块序号 % 17
        block_count = (len(audio) + BLOCK - 1) // BLOCK
        for block_idx in range(block_count):
            if block_idx >= pub_len:
                raise FormatError(f"{path.name}: 公钥耗尽（文件过大或损坏）")
            phase = block_idx % 17
            tables = self._phase_tables(phase, own_key, pub_key)
            pub_value = pub_key[block_idx]
            start = block_idx * BLOCK
            end = min(start + BLOCK, len(audio))
            for col, offset in enumerate(range(start, end)):
                out[offset] = tables[col][pub_value][audio[offset]]
        payload = bytes(out)
        return DecodeResult(payload=payload, container=sniff_container(payload[:64]), source=f"kgm-v{crypto_version}")
